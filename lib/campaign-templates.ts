export function renderTemplateString(
  value: string,
  variables: Record<string, string>,
) {
  return value.replace(/{{\s*([a-zA-Z0-9]+)\s*}}/g, (_, key: string) =>
    variables[key] === undefined ? `{{${key}}}` : variables[key],
  );
}

export function addTemplateDays(startDate: string, dayOffset: number) {
  const value = new Date(`${startDate}T00:00:00.000Z`);
  value.setUTCDate(value.getUTCDate() + dayOffset);
  return value.toISOString().slice(0, 10);
}

export function instantiateCampaignTemplate(
  template: CampaignTemplate,
  input: {
    brandName: string;
    startDate: string;
    variables: Record<string, string>;
  },
) {
  const defaults = Object.fromEntries(
    template.variables.map((item) => [item.key, item.defaultValue]),
  );
  const variables = {
    ...defaults,
    ...input.variables,
    brandName: input.brandName,
  };
  const render = (value: string) => renderTemplateString(value, variables);
  return {
    summary: render(template.description),
    objective: render(template.objective),
    audience: render(template.audience),
    offer: render(template.offer),
    startDate: input.startDate,
    endDate: addTemplateDays(input.startDate, template.durationDays),
    channels: template.channels,
    plan: {
      topics: template.topics.map(render),
      successMetrics: template.successMetrics.map(render),
      assumptions: [
        "Template variables and Brand Kit guidance are current",
        "All selected destination connections remain available",
      ],
      risks: [
        "Seasonal timing may require schedule adjustments",
        "Promotion language requires final reviewer approval",
      ],
      templateId: template.id,
      templateName: template.name,
      recommendedBudget: template.recommendedBudget,
      variables,
    },
    assets: template.assets.map((item) => ({
      ...item,
      title: render(item.title),
      body: render(item.body),
      scheduledAt: `${addTemplateDays(input.startDate, item.dayOffset)}T${String(item.hour).padStart(2, "0")}:00:00.000Z`,
    })),
  };
}
