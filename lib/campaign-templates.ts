import { z } from "zod";

export const templateVariableSchema = z.object({
  key: z.string().regex(/^[a-z][A-Za-z0-9]*$/),
  label: z.string().min(2),
  kind: z.enum(["text", "number", "url"]),
  defaultValue: z.string(),
  help: z.string().min(3),
  required: z.boolean().default(true),
});

export const templateAssetSchema = z.object({
  channel: z.string().min(2),
  type: z.string().min(2),
  title: z.string().min(3),
  body: z.string().min(10),
  dayOffset: z.number().int().min(0),
  hour: z.number().int().min(0).max(23).default(14),
});

export const campaignTemplateSchema = z.object({
  id: z.string().min(3),
  slug: z.string().regex(/^[a-z0-9-]+$/),
  name: z.string().min(3),
  description: z.string().min(10),
  category: z.enum(["Seasonal", "Lifecycle", "Launch", "Demand generation"]),
  occasion: z.string().min(3),
  badge: z.string().min(2),
  featured: z.boolean(),
  durationDays: z.number().int().min(1),
  channels: z.array(z.string()).min(1),
  audience: z.string().min(3),
  objective: z.string().min(3),
  offer: z.string().min(3),
  variables: z.array(templateVariableSchema),
  assets: z.array(templateAssetSchema).min(1),
  topics: z.array(z.string()).min(2),
  successMetrics: z.array(z.string()).min(1),
  recommendedBudget: z.number().int().min(0),
  updatedAt: z.string(),
});

export type CampaignTemplate = z.infer<typeof campaignTemplateSchema>;
export type CampaignTemplateAsset = z.infer<typeof templateAssetSchema>;
export type TemplateVariable = z.infer<typeof templateVariableSchema>;

const updatedAt = "2026-08-15T12:00:00.000Z";
const variable = (
  key: string,
  label: string,
  defaultValue: string,
  help: string,
  kind: "text" | "number" | "url" = "text",
) => ({ key, label, defaultValue, help, kind, required: true });

const asset = (
  channel: string,
  type: string,
  title: string,
  body: string,
  dayOffset: number,
  hour = 14,
) => ({ channel, type, title, body, dayOffset, hour });

